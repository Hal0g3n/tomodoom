#!/usr/bin/env python3
"""Generate the launcher icon from logo.svg. Re-run it after editing the logo.

Writes (all GENERATED, never edit by hand):
  res/drawable/ic_launcher_foreground.xml   adaptive foreground: the phone, emblem scaled to the 72dp visible area
  res/drawable/ic_launcher_monochrome.xml   themed-icon layer: only the jet (#383A3D) line work
  res/mipmap-*/ic_launcher.webp             legacy (API 24-25) icon: the emblem, cropped
  res/mipmap-*/ic_launcher_round.webp       legacy round icon: the phone on an eggshell circle

The adaptive background is @color/launcher_background (eggshell): the launcher mask replaces the
logo's floral-white field and emblem square. Needs rsvg-convert and Pillow.

Usage: python3 tools/launcher_icon/make_launcher_icon.py
"""
import copy
import io
import pathlib
import subprocess
import xml.etree.ElementTree as ET

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parents[1] / "app" / "src" / "main" / "res"
SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)

BACKDROP = 2                  # first two top-level shapes: the floral-white field and the emblem square
EMBLEM = (140, 232)           # emblem x/y and size in logo units; it maps onto the 72dp visible area
JET = "#383A3D"
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
ANDROID = "http://schemas.android.com/apk/res/android"
PALETTE = {"#FBF7EF": "floral_white", "#F7F0DE": "eggshell", "#585B5E": "charcoal", JET: "jet",
           "#8C8F92": "slate_grey"}  # CLAUDE.md §6.3: drawables use palette tokens, never raw hex


def colour(hex_value):
    return "@color/" + PALETTE[hex_value.upper()]  # KeyError = the logo left the palette


def tag(el):
    return el.tag.split("}")[-1]


def path_data(el):
    """SVG shape -> path data (rect, circle, ellipse, path)."""
    a = {k: float(v) for k, v in el.attrib.items() if k in ("x", "y", "width", "height", "rx", "cx", "cy", "r", "ry")}
    kind = tag(el)
    if kind == "path":
        return el.get("d")
    if kind == "rect":
        x, y, w, h, r = a.get("x", 0), a.get("y", 0), a["width"], a["height"], a.get("rx", 0)
        if not r:
            return f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}z"
        return (f"M{x + r:g},{y:g}h{w - 2 * r:g}a{r:g},{r:g} 0 0 1 {r:g},{r:g}v{h - 2 * r:g}"
                f"a{r:g},{r:g} 0 0 1 {-r:g},{r:g}h{-(w - 2 * r):g}a{r:g},{r:g} 0 0 1 {-r:g},{-r:g}"
                f"v{-(h - 2 * r):g}a{r:g},{r:g} 0 0 1 {r:g},{-r:g}z")
    rx, ry = (a["r"], a["r"]) if kind == "circle" else (a["rx"], a["ry"])
    cx, cy = a["cx"], a["cy"]
    return f"M{cx - rx:g},{cy:g}a{rx:g},{ry:g} 0 1 0 {2 * rx:g},0a{rx:g},{ry:g} 0 1 0 {-2 * rx:g},0z"


def vector_path(el, mono):
    fill = el.get("fill", "#000000")
    stroke = el.get("stroke", "none")
    if mono:  # keep only the jet parts of each shape
        fill = fill if fill.upper() == JET else "none"
        stroke = stroke if stroke.upper() == JET else "none"
        if fill == stroke == "none":
            return None
    attrs = {"pathData": path_data(el)}
    if fill != "none":
        attrs["fillColor"] = colour(fill)
    if stroke != "none":
        attrs.update(strokeColor=colour(stroke), strokeWidth=el.get("stroke-width", "1"))
        if el.get("stroke-linecap"):
            attrs["strokeLineCap"] = el.get("stroke-linecap")
    return "<path " + " ".join(f'android:{k}="{v}"' for k, v in attrs.items()) + " />"


def vector(root, mono):
    clips = {c.get("id"): path_data(c[0]) for c in root.iter(f"{{{SVG_NS}}}clipPath")}
    lines = []
    for el in [e for e in root if tag(e) != "defs"][BACKDROP:]:
        if tag(el) == "g":
            clip = el.get("clip-path", "")[5:-1]
            body = [p for p in (vector_path(c, mono) for c in el) if p]
            lines += ["<group>", f'    <clip-path android:pathData="{clips[clip]}" />']
            lines += ["    " + p for p in body] + ["</group>"]
        elif (p := vector_path(el, mono)):
            lines.append(p)
    span = EMBLEM[1] * 108 / 72                 # logo units across the 108dp canvas
    offset = 256 - span / 2
    inner = "\n".join("        " + line for line in lines)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/launcher_icon/make_launcher_icon.py'
            f' from logo.svg. Do not edit. -->\n<vector xmlns:android="{ANDROID}"\n'
            f'    android:width="108dp"\n    android:height="108dp"\n'
            f'    android:viewportWidth="{span:g}"\n    android:viewportHeight="{span:g}">\n'
            f'    <group android:translateX="{-offset:g}" android:translateY="{-offset:g}">\n'
            f"{inner}\n    </group>\n</vector>\n")


def legacy_svg(root, round_icon):
    svg = copy.deepcopy(root)
    shapes = [e for e in svg if tag(e) != "defs"]
    for el in shapes[:1 if not round_icon else BACKDROP]:
        svg.remove(el)
    pad = 10
    svg.set("viewBox", f"{EMBLEM[0] - pad} {EMBLEM[0] - pad} {EMBLEM[1] + 2 * pad} {EMBLEM[1] + 2 * pad}")
    if round_icon:
        circle = ET.Element(f"{{{SVG_NS}}}circle", cx="256", cy="256", r=str(EMBLEM[1] / 2), fill="#F7F0DE")
        svg.insert(1, circle)
    return ET.tostring(svg)


def render(svg_bytes, size, out):
    png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size)], input=svg_bytes,
                         capture_output=True, check=True).stdout
    Image.open(io.BytesIO(png)).save(out, "WEBP", lossless=True)


def main():
    root = ET.parse(HERE / "logo.svg").getroot()
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector(root, mono=False))
    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(vector(root, mono=True))
    for density, size in DENSITIES.items():
        folder = RES / f"mipmap-{density}"
        render(legacy_svg(root, False), size, folder / "ic_launcher.webp")
        render(legacy_svg(root, True), size, folder / "ic_launcher_round.webp")
    print("make_launcher_icon: wrote the adaptive layers and", 2 * len(DENSITIES), "legacy icons")


if __name__ == "__main__":
    main()
